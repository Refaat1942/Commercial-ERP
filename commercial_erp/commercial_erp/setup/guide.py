def _rows_html():
	out = []
	for group, term, meaning, example in TERMS:
		out.append(
			"<tr data-g='{g}'><td class='g'>{g}</td><td class='t'>{t}</td><td>{m}</td><td class='e'>{e}</td></tr>".format(
				g=html.escape(group), t=html.escape(term), m=html.escape(meaning), e=html.escape(example)
			)
		)
	return "".join(out)


def block_html():
	return f"""
<div class="ce-guide" dir="rtl">
  <input type="search" class="form-control ce-guide-search" placeholder="ابحث عن مصطلح... (مثال: مرتجع، مدين، مخزن)">
  <table class="table ce-guide-table">
    <thead><tr><th>القسم</th><th>المصطلح</th><th>معناه ببساطة</th><th>مثال</th></tr></thead>
    <tbody>{_rows_html()}</tbody>
  </table>
</div>"""


BLOCK_STYLE = """
.ce-guide-search{margin-bottom:12px;height:44px;border-radius:12px;font-size:15px}
.ce-guide-table{background:#fff;border-radius:12px;overflow:hidden}
.ce-guide-table th{background:#E6F2F1;color:#084F49;font-weight:700}
.ce-guide-table td{vertical-align:top;line-height:1.7}
.ce-guide-table td.t{font-weight:700;color:#0B6B63;white-space:nowrap}
.ce-guide-table td.g{color:#4D605C;white-space:nowrap}
.ce-guide-table td.e{color:#4D605C}
"""
BLOCK_SCRIPT = """
const box = root_element.querySelector('.ce-guide-search');
const rows = root_element.querySelectorAll('tbody tr');
box && box.addEventListener('input', () => {
  const q = box.value.trim();
  rows.forEach(r => { r.style.display = (!q || r.textContent.includes(q)) ? '' : 'none'; });
});
"""


def ensure():
	if not frappe.db.exists("Custom HTML Block", BLOCK_NAME):
		frappe.get_doc(
			{
				"doctype": "Custom HTML Block",
				"name": BLOCK_NAME,
				"private": 0,
				"html": block_html(),
				"style": BLOCK_STYLE,
				"script": BLOCK_SCRIPT,
			}
		).insert(ignore_permissions=True)
	else:  # keep the text current when the guide is extended
		frappe.db.set_value(
			"Custom HTML Block",
			BLOCK_NAME,
			{"html": block_html(), "style": BLOCK_STYLE, "script": BLOCK_SCRIPT},
		)
	blocks = [
		{
			"id": "g1",
			"type": "header",
			"data": {"text": '<span class="h4">دليل المصطلحات</span>', "col": 12},
		},
		{"id": "g2", "type": "custom_block", "data": {"custom_block_name": BLOCK_NAME, "col": 12}},
	]
	if frappe.db.exists("Workspace", GUIDE_WORKSPACE):
		frappe.db.set_value(
			"Workspace", GUIDE_WORKSPACE, "content", json.dumps(blocks), update_modified=False
		)
		return
	frappe.get_doc(
		{
			"doctype": "Workspace",
			"name": GUIDE_WORKSPACE,
			"label": GUIDE_WORKSPACE,
			"title": "Terms Guide",
			"module": "Shop",
			"public": 1,
			"type": "Workspace",
			"icon": "book-open",
			"sequence_id": 0.6,
			"content": json.dumps(blocks),
			"custom_blocks": [{"custom_block_name": BLOCK_NAME, "label": BLOCK_NAME}],
		}
	).insert(ignore_permissions=True)
